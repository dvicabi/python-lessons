# תרגיל 30 | לולאות for | מתקדם
# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

a = 8
b = 5
for i in range(7, 0, -1):
    if i % 2 == 0:
        a += b
        b += 1
    else:
        a -= i
        b *= 2
    print(a, b)
print("End", a, b)

