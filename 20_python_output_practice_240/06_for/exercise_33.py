# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

a = 7
b = 6
for i in range(10, 0, -1):
    if i % 2 == 0:
        a += b
        b += 1
    else:
        a -= i
        b *= 2
    print(a, b)

