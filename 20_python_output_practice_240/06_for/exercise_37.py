# תרגיל 37 | לולאות for | אתגר
# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

for i in range(1, 7):
    for j in range(1, i + 1):
        print(i * j, end="|")
    print()

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 1|
# 2|4|
# 3|6|9|
# 4|8|12|16|
# 5|10|15|20|25|
# 6|12|18|24|30|36|
# <<< END EXPECTED OUTPUT
