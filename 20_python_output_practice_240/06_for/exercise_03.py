# תרגיל 03 | לולאות for | קל
# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

a = 4
b = 3
for i in range(7, 0, -1):
    if i % 2 == 0:
        a += b
        b += 1
    else:
        a -= i
        b *= 2
    print(a, b)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# -3 6
# 3 7
# -2 14
# 12 15
# 9 30
# 39 31
# 38 62
# <<< END EXPECTED OUTPUT
# ערכים סופיים: a=38, b=62
