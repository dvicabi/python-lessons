# תרגיל 22 | לולאות for | מתקדם
# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

x = 22
for i in range(1, 8):
    if i % 2 == 0:
        x -= i
    else:
        x += i
    print(i, x)
print("Final", x)

