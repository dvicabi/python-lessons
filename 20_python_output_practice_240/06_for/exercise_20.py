# תרגיל 20 | לולאות for | בינוני
# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

a = 7
b = 4
for i in range(6, 0, -1):
    if i % 2 == 0:
        a += b
        b += 1
    else:
        a -= i
        b *= 2
    print(a, b)
print("End", a, b)

