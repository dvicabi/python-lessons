# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

x = 4
y = 1
for i in range(1, 8):
    if i % 2 == 0:
        x *= 2
    else:
        y += x
    if x > 20:
        x -= 10
    print(i, x, y)
print("Final", x, y)

