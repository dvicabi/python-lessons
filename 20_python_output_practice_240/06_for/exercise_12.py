# תרגיל 12 | לולאות for | בינוני
# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

x = 20
for i in range(1, 7):
    if i % 2 == 0:
        x -= i
    else:
        x += i
    print(i, x)
print("Final", x)

