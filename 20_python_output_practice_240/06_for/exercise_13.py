# תרגיל 13 | לולאות for | בינוני
# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

a = 5
b = 4
for i in range(8, 0, -1):
    if i % 2 == 0:
        a += b
        b += 1
    else:
        a -= i
        b *= 2
    print(a, b)

