# תרגיל 10 | לולאות for | קל
# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

a = 6
b = 3
for i in range(5, 0, -1):
    if i % 2 == 0:
        a += b
        b += 1
    else:
        a -= i
        b *= 2
    print(a, b)
print("End", a, b)

