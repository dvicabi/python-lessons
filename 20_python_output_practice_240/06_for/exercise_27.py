# תרגיל 27 | לולאות for | מתקדם
# מה הפלט המדויק? הכינו טבלת מעקב לכל איטרציה.

for i in range(1, 6):
    for j in range(1, i + 1):
        print(i * j, end="|")
    print()

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 1|
# 2|4|
# 3|6|9|
# 4|8|12|16|
# 5|10|15|20|25|
# <<< END EXPECTED OUTPUT
