# תרגיל 06 | לולאות while | קל
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 3
y = 20
while x < y:
    print(x, y)
    x += 3
    y -= 2
print("End", x, y)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 3 20
# 6 18
# 9 16
# 12 14
# End 15 12
# <<< END EXPECTED OUTPUT
# ערכים סופיים: x=15, y=12
