# תרגיל 32 | לולאות while | אתגר
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 4
total = 0
while x <= 11:
    total += x
    print(x, total)
    x += 1
print(total)

