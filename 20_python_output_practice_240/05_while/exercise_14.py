# תרגיל 14 | לולאות while | בינוני
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 1
s = 0
while x <= 12:
    if x % 2 == 0:
        s += x
    else:
        s -= x
    x += 1
print(s, x)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 6 13
# <<< END EXPECTED OUTPUT
# ערכים סופיים: s=6, x=13
