# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 6
y = 4
while x < 29:
    if x % 4 == 0:
        y += x // 2
    else:
        y *= 2
    print(x, y)
    x += y % 5 + 2
print(x + y)

