# תרגיל 26 | לולאות while | מתקדם
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 5
y = 26
while x < y:
    print(x, y)
    x += 5
    y -= 4
print("End", x, y)

