# תרגיל 22 | לולאות while | מתקדם
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 3
total = 0
while x <= 9:
    total += x
    print(x, total)
    x += 1
print(total)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 3 3
# 4 7
# 5 12
# 6 18
# 7 25
# 8 33
# 9 42
# 42
# <<< END EXPECTED OUTPUT
# ערכים סופיים: x=10, total=42
