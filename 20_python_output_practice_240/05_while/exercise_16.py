# תרגיל 16 | לולאות while | בינוני
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 4
y = 23
while x < y:
    print(x, y)
    x += 4
    y -= 3
print("End", x, y)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 4 23
# 8 20
# 12 17
# End 16 14
# <<< END EXPECTED OUTPUT
# ערכים סופיים: x=16, y=14
