# תרגיל 04 | לולאות while | קל
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 1
s = 0
while x <= 10:
    if x % 2 == 0:
        s += x
    else:
        s -= x
    x += 1
print(s, x)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 5 11
# <<< END EXPECTED OUTPUT
# ערכים סופיים: s=5, x=11
