# תרגיל 23 | לולאות while | מתקדם
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 21
while x > 0:
    print(x, end="|")
    x -= 6
print("END")

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 21|15|9|3|END
# <<< END EXPECTED OUTPUT
# ערכים סופיים: x=-3
