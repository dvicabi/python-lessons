# תרגיל 34 | לולאות while | אתגר
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 1
s = 0
while x <= 16:
    if x % 2 == 0:
        s += x
    else:
        s -= x
    x += 1
print(s, x)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 8 17
# <<< END EXPECTED OUTPUT
