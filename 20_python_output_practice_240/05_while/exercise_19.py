# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 4
y = 2
while x < 23:
    if x % 4 == 0:
        y += x // 2
    else:
        y *= 2
    print(x, y)
    x += y % 5 + 2
print(x + y)

