# תרגיל 11 | לולאות while | בינוני
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 3
while x <= 13:
    print(x)
    x += 3
print("End", x)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 3
# 6
# 9
# 12
# End 15
# <<< END EXPECTED OUTPUT
