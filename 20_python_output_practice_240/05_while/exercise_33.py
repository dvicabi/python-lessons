# תרגיל 33 | לולאות while | אתגר
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 24
while x > 0:
    print(x, end="|")
    x -= 7
print("END")

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 24|17|10|3|END
# <<< END EXPECTED OUTPUT
# ערכים סופיים: x=-4
