# תרגיל 01 | לולאות while | קל
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 2
while x <= 10:
    print(x)
    x += 2
print("End", x)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 2
# 4
# 6
# 8
# 10
# End 12
# <<< END EXPECTED OUTPUT
# ערכים סופיים: x=12
