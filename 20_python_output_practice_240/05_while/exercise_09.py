# תרגיל 09 | לולאות while | קל
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 3
y = 1
while x < 20:
    if x % 4 == 0:
        y += x // 2
    else:
        y *= 2
    print(x, y)
    x += y % 5 + 2
print(x + y)

