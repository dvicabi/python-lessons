# תרגיל 13 | לולאות while | בינוני
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 18
while x > 0:
    print(x, end="|")
    x -= 5
print("END")

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 18|13|8|3|END
# <<< END EXPECTED OUTPUT
# ערכים סופיים: x=-2
