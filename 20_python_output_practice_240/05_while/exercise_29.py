# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 5
y = 3
while x < 26:
    if x % 4 == 0:
        y += x // 2
    else:
        y *= 2
    print(x, y)
    x += y % 5 + 2
print(x + y)

