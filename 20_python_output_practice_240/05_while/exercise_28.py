# תרגיל 28 | לולאות while | מתקדם
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

i = 1
while i <= 5:
    j = 1
    while j <= i:
        print(i * j, end="|")
        j += 1
    print()
    i += 1

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 1|
# 2|4|
# 3|6|9|
# 4|8|12|16|
# 5|10|15|20|25|
# <<< END EXPECTED OUTPUT
# ערכים סופיים: i=6, j=5
