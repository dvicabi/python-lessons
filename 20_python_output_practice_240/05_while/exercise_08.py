# תרגיל 08 | לולאות while | קל
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

i = 1
while i <= 3:
    j = 1
    while j <= i:
        print(i * j, end="|")
        j += 1
    print()
    i += 1

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 1|
# 2|4|
# 3|6|9|
# <<< END EXPECTED OUTPUT
# ערכים סופיים: i=4, j=3
