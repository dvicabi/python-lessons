# תרגיל 18 | לולאות while | בינוני
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

i = 1
while i <= 4:
    j = 1
    while j <= i:
        print(i * j, end="|")
        j += 1
    print()
    i += 1

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 1|
# 2|4|
# 3|6|9|
# 4|8|12|16|
# <<< END EXPECTED OUTPUT
# ערכים סופיים: i=5, j=4
