# תרגיל 36 | לולאות while | אתגר
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 6
y = 29
while x < y:
    print(x, y)
    x += 6
    y -= 5
print("End", x, y)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 6 29
# 12 24
# 18 19
# End 24 14
# <<< END EXPECTED OUTPUT
