# תרגיל 24 | לולאות while | מתקדם
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 1
s = 0
while x <= 14:
    if x % 2 == 0:
        s += x
    else:
        s -= x
    x += 1
print(s, x)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 7 15
# <<< END EXPECTED OUTPUT
# ערכים סופיים: s=7, x=15
