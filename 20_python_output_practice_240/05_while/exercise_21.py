# תרגיל 21 | לולאות while | מתקדם
# מה הפלט המדויק? מלאו טבלת מעקב והסבירו מתי הלולאה נעצרת.

x = 4
while x <= 16:
    print(x)
    x += 4
print("End", x)

# --------------------------------------
# פתרון סופי:
# >>> EXPECTED OUTPUT
# 4
# 8
# 12
# 16
# End 20
# <<< END EXPECTED OUTPUT
# ערכים סופיים: x=20
