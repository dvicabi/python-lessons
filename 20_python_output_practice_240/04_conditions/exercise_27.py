# איזה ענף תנאי מתבצע ומה הפלט המדויק? הכינו טבלת מעקב.

x = 13
y = 12
if x % 2 == 0:
    y += x
else:
    x -= 3
if x > y:
    print(x - y)
else:
    print(y - x)
print(x, y)

