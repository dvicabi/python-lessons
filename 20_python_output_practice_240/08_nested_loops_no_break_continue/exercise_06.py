# אתגר 06 | while חיצונית ו-for שמשנה את תנאי ההמשך
# רמה: מתקדם | לולאות מקוננות: 2
# משימה: חשבו את הפלט המדויק ובנו טבלת מעקב של המשתנים.
# הפתרון נמצא בתחתית הקובץ. קודם נסו לפתור בלי להריץ.

i = 1
a = 6
b = 2

while i <= 4:
    for j in range(1, i + 2):
        if (a + j) % 3 == 0:
            b += i * j
        else:
            a += j - b % 3

    print(i, a, b)
    i += 1

print("FINAL", a - b)

