# רמה: קשה | לולאות מקוננות: 2
# משימה: חשבו את הפלט המדויק וערכו טבלת מעקב לכל המשתנים.
# הקפידו על סדר ביצוע התנאים, וסיימו רק כשתנאי הלולאה מפסיק להתקיים.

x = 4

for i in range(1, 5):
    row = ""

    for j in range(1, i + 4):
        if (i * j + x) % 4 < 2:
            row += "#"
            x += j
        else:
            row += "."
            x += i

    print(i, row, x)

print("FINAL", x)

