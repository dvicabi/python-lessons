# רמז: טבלת מעקב מלאה עדיפה מניסיון לנחש את התוצאה.

a = 11
b = 5
c = 2
times = 0

for i in range(1, 4):
    for j in range(i, i + 3):
        k = 1

        while k <= j + 1:
            if (a + k) % 3 == 0:
                a -= b % 4
                c += i
            elif (b + j) % 2 == 0:
                b += k
                a += i
            else:
                c -= j
                b += i

            if c < 0:
                c += j + 2

            times += 1
            k += 1

    print(i, a, b, c, times)

print("CHECK", a + b + c - times)

