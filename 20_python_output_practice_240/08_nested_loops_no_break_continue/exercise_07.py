# אתגר 07 | שתי לולאות while עם קפיצות של 2
# רמה: מתקדם | לולאות מקוננות: 2
# משימה: חשבו את הפלט המדויק ובנו טבלת מעקב של המשתנים.
# הפתרון נמצא בתחתית הקובץ. קודם נסו לפתור בלי להריץ.

i = 2
score = 7
count = 0

while i <= 4:
    j = i + 1

    while j >= 1:
        if (i * j + score) % 4 == 0:
            score += i + j
        else:
            score -= i

        count += 1
        j -= 2

    print(i, score, count)
    i += 1

print("FINAL", score + count)

