# שימו לב: תנאים בתוך הלולאות עשויים להשפיע על כל סיבוב עתידי.

n = 28
s = 0
i = 1

while i <= 4:
    for j in range(i + 3, 0, -2):
        if n % 4 == 0:
            n //= 2
            s += j
        elif (n + j) % 3 == 0:
            n += j
            s -= i
        else:
            n -= i
            s += n % 5

    print(i, n, s)
    i += 1

print("FINAL", n + s)

