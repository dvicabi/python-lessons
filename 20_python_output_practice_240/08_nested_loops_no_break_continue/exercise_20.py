# אתגר 20 | אחרי כל while גם תנאי עצמאי
# רמה: קשה | לולאות מקוננות: 2
# משימה: חשבו את הפלט המדויק וערכו טבלת מעקב לכל המשתנים.
# הקפידו על סדר ביצוע התנאים, וסיימו רק כשתנאי הלולאה מפסיק להתקיים.

x = 14
y = 4

for i in range(5, 1, -1):
    j = 1

    while j <= i + 2:
        if j % 2 == 0:
            x += i * j - y
        else:
            y += x % 5
            x -= j

        if x % 3 == 0:
            y += i
        else:
            y -= 1

        j += 1

    if (x + y) % 2 == 0:
        x //= 2
    else:
        y += i

    print(i, x, y)

print("FINAL", x + y)

