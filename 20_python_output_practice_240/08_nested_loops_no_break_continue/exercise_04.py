# אתגר 04 | ספירה לאחור עם while פנימית
# רמה: מתקדם | לולאות מקוננות: 2
# משימה: חשבו את הפלט המדויק ובנו טבלת מעקב של המשתנים.
# הפתרון נמצא בתחתית הקובץ. קודם נסו לפתור בלי להריץ.

x = 13
y = 2

for i in range(6, 1, -1):
    j = 1
    while j <= i:
        if (i + j) % 2 == 0:
            x += i - j
        else:
            x -= j

        if x % 5 == 0:
            y += i

        j += 1

    print(i, x, y)

print("FINAL", x + y)

