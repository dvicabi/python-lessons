# אתגר 22 | while כפולה ומדד התקדמות משתנה
# רמה: קשה מאוד | לולאות מקוננות: 2
# משימה: חשבו את הפלט המדויק וסכמו את השינויים בטבלת מעקב.
# שימו לב: תנאים בתוך הלולאות עשויים להשפיע על כל סיבוב עתידי.

a = 10
b = 5
steps = 0
i = 1

while i <= 5:
    j = i + 1
    while j > 0:
        if (a + b + j) % 3 == 0:
            a += j - i
            b += 1
        elif a % 2 == 0:
            a //= 2
            b += i
        else:
            a += i
            b -= 1

        steps += 1
        j -= 1

    print(i, a, b, steps)
    i += 1

print("FINAL", a + b + steps)

