# הפתרון נמצא בתחתית הקובץ. קודם נסו לפתור בלי להריץ.

total = 6

for i in range(1, 4):
    for j in range(1, i + 2):
        if (i * j) % 3 == 0:
            total += i + j
        else:
            total -= j
    print(i, total)

print("FINAL", total)

